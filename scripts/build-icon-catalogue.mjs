/**
 * Builds the searchable icon catalogue from `lucide-static`.
 *
 * Run with `npm run icons` after bumping that package. It writes four files,
 * all committed, so a build never depends on this script having been run:
 *
 *   public/icons/lucide-<version>.svg   every icon as a <symbol>, fetched on demand
 *   public/icons/lucide-<version>.json  [name, tags] rows the picker searches
 *   lib/icon-catalogue.generated.ts     the two URLs above
 *   lib/api/icon-catalogue-names.generated.ts  the names, for the server to check against
 *
 * The version is in the file name because both files are served immutable.
 */
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "node_modules", "lucide-static");
const outDir = path.join(root, "public", "icons");

const SYMBOL_ATTRS =
  'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';

/** The drawing inside an icon file, without its comment or its <svg> wrapper. */
function innerMarkup(svg) {
  const open = svg.indexOf(">", svg.indexOf("<svg"));
  const close = svg.lastIndexOf("</svg>");
  return svg
    .slice(open + 1, close)
    .replaceAll(/\s*\n\s*/g, "")
    .replaceAll(" />", "/>");
}

const { version } = JSON.parse(await readFile(path.join(source, "package.json"), "utf8"));
const tags = JSON.parse(await readFile(path.join(source, "tags.json"), "utf8"));

const files = (await readdir(path.join(source, "icons")))
  .filter((file) => file.endsWith(".svg"))
  .sort((a, b) => a.localeCompare(b, "en"));

const symbols = [];
const index = [];
for (const file of files) {
  const name = file.slice(0, -".svg".length);
  const svg = await readFile(path.join(source, "icons", file), "utf8");
  symbols.push(`<symbol id="${name}" ${SYMBOL_ATTRS}>${innerMarkup(svg)}</symbol>`);
  index.push([name, (tags[name] ?? []).join(" ").toLowerCase()]);
}

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const base = `lucide-${version}`;
await writeFile(
  path.join(outDir, `${base}.svg`),
  `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>\n`,
);
await writeFile(path.join(outDir, `${base}.json`), `${JSON.stringify(index)}\n`);

const banner = "// Generated by scripts/build-icon-catalogue.mjs — do not edit by hand.\n\n";

await writeFile(
  path.join(root, "lib", "icon-catalogue.generated.ts"),
  `${banner}export const CATALOGUE_SPRITE_URL = "/icons/${base}.svg";\n` +
    `export const CATALOGUE_INDEX_URL = "/icons/${base}.json";\n`,
);

const names = index.map(([name]) => `  "${name}",\n`).join("");
await writeFile(
  path.join(root, "lib", "api", "icon-catalogue-names.generated.ts"),
  `${banner}export const CATALOGUE_NAMES: ReadonlySet<string> = new Set([\n${names}]);\n`,
);

console.log(`${index.length} icons from lucide-static ${version}`);
